  for (const kind of ['standard', 'scout', 'engineer', 'heavy']) {
    await page.locator(`[data-vehicle="${kind}"]`).tap();
    await page.waitForFunction(() => document.querySelector('#vehiclePreview').dataset.ready === 'true');
    assert.equal(await page.locator('#selectVehicle').isDisabled(), kind !== 'standard');
  }
  await page.screenshot({ path: 'artifacts/published-garage.png' });
  await page.locator('#closeGarage').tap();
  await page.locator('#careerButton').tap();
  await page.locator('#careerDialog').waitFor({ state: 'visible' });
  assert.match(await page.locator('#careerSummary').textContent(), /累计荣誉/);
  await page.getByRole('button', { name: '坦克工厂', exact: true }).tap();
  assert.equal(await page.locator('[data-upgrade]').count(), 5);
  await page.screenshot({ path: 'artifacts/published-factory.png' });
  await page.locator('#closeCareer').tap();
  await page.locator('#soloButton').tap();
  await page.locator('#hud').waitFor({ state: 'visible' });
  await page.waitForFunction(() => /敌军/.test(document.querySelector('#enemyCount')?.textContent || ''), null, { timeout: 20000 });
  assert.match(await page.locator('#enemyCount').textContent(), /敌军/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('#modeName').textContent(), '经典模式');
  assert.equal(await page.locator('#enemyBaseCard').isVisible(), false);
  assert.equal(await page.locator('.player-card').count(), 0);
  assert.equal(await page.locator('#localTankStatus').isVisible(), true);
  // 出生点的友塔位于侧面，横屏确认模型上方标签，随后恢复竖屏检查操作。
  await page.setViewportSize({ width: 844, height: 390 });
  await page.locator('.site-label[data-team=player]').first().waitFor({ state: 'visible' });
  await page.screenshot({ path: 'artifacts/published-towers.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('#score').isVisible(), false);
  const cdp = await context.newCDPSession(page);
  assert.equal(await pinchCameraControls(page, cdp), 1);
  await page.touchscreen.tap(195, 380);
  await page.touchscreen.tap(195, 380);
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => visualViewport.scale), 1);
  assert.match(await page.locator('#pickupLabels [data-power=heal]').textContent(), /满血无需维修/);
  await page.screenshot({ path: 'artifacts/published-battle.png' });
  const stick = await page.locator('#joystick').boundingBox();
  const driveTouch = { id: 1, x: stick.x + stick.width / 2, y: stick.y + 12 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [driveTouch] });
  await tapWhileHolding(page, cdp, '#boostToggle', [driveTouch]);
  assert.equal(await page.locator('#boostToggle').getAttribute('aria-pressed'), 'true');
  await page.waitForFunction(() => Number(document.querySelector('#staminaMeter').getAttribute('aria-valuenow')) < 95);
  await tapWhileHolding(page, cdp, '#chargeToggle', [driveTouch]);
  assert.equal(await page.locator('#chargeToggle').getAttribute('aria-pressed'), 'true');
  await tapWhileHolding(page, cdp, '#boostToggle', [driveTouch]);
  assert.equal(await page.locator('#boostToggle').getAttribute('aria-pressed'), 'false');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  const fire = await page.locator('#fireButton').boundingBox();
  const chargeTouch = { id: 3, x: fire.x + fire.width / 2, y: fire.y + fire.height / 2 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [chargeTouch] });
  await page.waitForFunction(() => document.querySelector('#touchReload').textContent === '松开发射');
  await page.screenshot({ path: 'artifacts/published-charge.png' });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForFunction(() => /s$/.test(document.querySelector('#touchReload').textContent));
  assert.equal(await page.locator('#fireButton').evaluate(e => e.classList.contains('charging')), false);
  await page.waitForFunction(() => document.querySelector('#touchReload').textContent === '蓄力');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [chargeTouch] });
  await page.waitForFunction(() => document.querySelector('#fireButton').classList.contains('charging'));
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  await page.waitForFunction(() => document.querySelector('#touchReload').textContent === '蓄力');
  assert.equal(await page.locator('#radarPanel').evaluate(e => getComputedStyle(e).backgroundColor), 'rgba(0, 0, 0, 0)');
  await page.locator('#mapToggle').tap();
  assert.equal(await page.locator('#mapToggle').getAttribute('aria-expanded'), 'true');
  await page.locator('#mapToggle').tap();
  await page.locator('#pauseButton').tap();
  assert.equal(await page.locator('#lives').isVisible(), true);
  assert.equal(await page.locator('#score').isVisible(), true);
  await page.locator('#backMenu').tap();
  await page.locator('#modeDefense').tap();
  await page.locator('#soloButton').tap();
  await page.waitForFunction(() => /敌军/.test(document.querySelector('#enemyCount')?.textContent || ''), null, { timeout: 20000 });
  assert.equal(await page.locator('#modeName').textContent(), '防守模式');
  assert.equal(await page.locator('#enemyBaseCard').isVisible(), false);
  await page.screenshot({ path: 'artifacts/published-defense.png' });
  await page.locator('#pauseButton').tap();
  await page.locator('#backMenu').tap();
  // 用正式的导入入口迁移旧档案，再验证金币解锁、选用及刷新后的记忆。
  await page.locator('#careerButton').tap();
  await page.locator('[data-career-tab="record"]').tap();
  await page.locator('#profileFile').setInputFiles({ name: 'old-profile.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(funded)) });
  await page.locator('#confirmImport').tap();
  await page.locator('#closeCareer').tap();
  await page.locator('#vehicleButton').tap();
  await page.locator('[data-vehicle="heavy"]').tap();
  await page.locator('#selectVehicle').tap();
  await page.locator('#vehicleDialog').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#selectedVehicleName').textContent(), '重型突破坦克');
  const profile = await page.evaluate(() => JSON.parse(localStorage.getItem('tb-profile-v1')));
  assert.equal(profile.version, 2); assert.equal(profile.coins, 1240); assert.equal(profile.honor, 5000);
  assert.deepEqual(profile.unlockedVehicles, ['standard', 'heavy']);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#selectedVehicleName').textContent(), '重型突破坦克');
  await page.locator('#modeDefense').tap();
  await page.locator('#difficulty').selectOption('casual');
  await page.locator('#mapSize').selectOption('large');
  await page.locator('#hostButton').tap();
  await page.locator('#lobbyDialog').waitFor({ state: 'visible', timeout: 25000 });
