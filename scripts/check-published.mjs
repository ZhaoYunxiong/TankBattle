const funded = { version: 1, id: 'published-vehicle-check', honor: 5000, coins: 1600, earned: 1600, battles: 0, wins: 0, upgrades: { armor: 0, mobility: 0, reload: 0, baseArmor: 0, repair: 0 }, records: [], settled: [] };
